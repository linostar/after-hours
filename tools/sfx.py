RATE = 22050
PEAK = 0.9
# The sound effects together must stay under this (the web build stays small).
MAX_TOTAL_BYTES = 1024 * 1024


class SfxError(Exception):
    pass


def lowpass(samples, cutoffs):
    """One-pole low-pass filter with a per-sample cutoff in Hz."""
    out, y = [], 0.0
    for x, fc in zip(samples, cutoffs):
        y += (1.0 - math.exp(-2.0 * math.pi * fc / RATE)) * (x - y)
        out.append(y)
    return out


def bandpass(samples, centre, q):
    """RBJ biquad band-pass (constant 0 dB peak gain) at `centre` Hz with quality `q`."""
    w = 2 * math.pi * centre / RATE
    alpha = math.sin(w) / (2 * q)
    b0, b2, a0, a1, a2 = alpha, -alpha, 1 + alpha, -2 * math.cos(w), 1 - alpha
    out, x1, x2, y1, y2 = [], 0.0, 0.0, 0.0, 0.0
    for x in samples:
        y = (b0 * x + b2 * x2 - a1 * y1 - a2 * y2) / a0
        out.append(y)
        x2, x1, y2, y1 = x1, x, y1, y
    return out


def envelope(n, attack, release):
    """Linear attack, then linear release over the last `release` seconds."""
    a, r = max(1, int(attack * RATE)), max(1, int(release * RATE))
    return [min(1.0, i / a, (n - i) / r) for i in range(n)]


def lerp_curve(points, n):
    """Piecewise-linear curve through (time_fraction, value) points."""
    out = []
    for i in range(n):
        t = i / max(1, n - 1)
        for (t0, v0), (t1, v1) in zip(points, points[1:]):
            if t0 <= t <= t1:
                out.append(v0 + (v1 - v0) * (t - t0) / max(1e-9, t1 - t0))
                break
    return out


def oscillate(freqs, shape):
    """A wave following the per-sample frequency curve `freqs`; shape(phase 0..1) -> -1..1."""
    phase, out = 0.0, []
    for f in freqs:
        phase = (phase + f / RATE) % 1.0
        out.append(shape(phase))
    return out


def place(buf, samples, at, gain=1.0):
    """Adds `samples` into `buf` from `at` seconds on, growing `buf` as needed."""
    start = int(at * RATE)
    if len(buf) < start + len(samples):
        buf.extend([0.0] * (start + len(samples) - len(buf)))
    for i, s in enumerate(samples):
        buf[start + i] += s * gain
    return buf


def ping(freq, seconds, decay, partials=((1.0, 1.0),), attack=0.002):
    """A struck tone: sine partials (frequency multiple, amplitude) under an exponential decay."""
    n, a = int(seconds * RATE), max(1, int(attack * RATE))
    return [min(1.0, i / a) * math.exp(-decay * i / RATE)
            * sum(amp * math.sin(2 * math.pi * freq * mult * i / RATE) for mult, amp in partials if freq * mult < RATE / 2)
            for i in range(n)]


def sweep(start_hz, end_hz, seconds, shape, attack, release):
    """A tone gliding from start_hz to end_hz with a linear envelope."""
    n = int(seconds * RATE)
    raw = oscillate(lerp_curve([(0, start_hz), (1, end_hz)], n), shape)
    return [s * e for s, e in zip(raw, envelope(n, attack, release))]


def noise(seconds, rng, cutoffs, decay=0.0, attack=0.002, release=0.02):
    """Low-passed white noise; `cutoffs` is a lerp_curve point list for the cutoff in Hz."""
    n = int(seconds * RATE)
    raw = lowpass([rng.uniform(-1.0, 1.0) for _ in range(n)], lerp_curve(cutoffs, n))
    env = envelope(n, attack, release)
    return [s * e * math.exp(-decay * i / RATE) for i, (s, e) in enumerate(zip(raw, env))]


def highpassed(samples):
    """A first difference: keeps the bright part of a sound (clicks, scrapes)."""
    out, last = [], 0.0
    for x in samples:
        out.append(x - last)
        last = x
    return out


def thump(freq=110.0, seconds=0.16, drop=1.0, decay=18.0):
    """A low drum-like hit: a sine falling `drop` octaves fast, decaying."""
    n, phase, out = int(seconds * RATE), 0.0, []
    for i in range(n):
        phase += freq * (1.0 + drop * math.exp(-30.0 * i / RATE)) / RATE
        out.append(math.sin(2 * math.pi * phase) * math.exp(-decay * i / RATE))
    return out


def sine(p):
    return math.sin(2 * math.pi * p)


def square(p):
    return 1.0 if p < 0.5 else -1.0


def triangle(p):
    return 4.0 * abs(p - 0.5) - 1.0


def saw(p):
    return 2.0 * p - 1.0


def pulse(width):
    return lambda p: 1.0 if p < width else -width / (1.0 - width)


BELL = ((1.0, 1.0), (2.76, 0.35), (5.4, 0.15))
GLASS = ((1.0, 1.0), (2.4, 0.4))
# A plate of steel: strongly inharmonic partials.
STEEL = ((1.0, 1.0), (2.32, 0.7), (4.25, 0.45), (6.63, 0.3), (9.38, 0.18))


def note_hz(semitones_from_a4):
    return 440.0 * 2 ** (semitones_from_a4 / 12)


def arpeggio(notes, gap, seconds, decay, partials):
    buf = []
    for i, semis in enumerate(notes):
        place(buf, ping(note_hz(semis), seconds, decay, partials), i * gap)
    return buf


def mix(*parts):
    """Adds (samples, at seconds, gain) parts into one buffer."""
    buf = []
    for samples, at, gain in parts:
        place(buf, samples, at, gain)
    return buf


def knock(rng, freq=180.0, seconds=0.09):
    """A knock on wood: a short low ping with a click of noise."""
    return mix((ping(freq, seconds, 45.0, WOOD), 0, 1.0), (noise(0.02, rng, [(0, 4000), (1, 1500)], decay=80.0), 0, 0.5))


# A hollow wooden block (the knocks, the tiptoes, the door).
WOOD = ((1.0, 1.0), (2.8, 0.25), (5.1, 0.08))
# Pizzicato strings and a vibraphone: the caper band of tools/music.py, echoed in the stingers.
PIZZ = ((1.0, 1.0), (2.0, 0.45), (3.0, 0.2), (4.0, 0.08))
VIBES = ((1.0, 1.0), (4.0, 0.12), (10.0, 0.03))

# Notes used below, as semitones from A4.
C4, F4, A4, C5, Eb5, F5, Gb5, A5, C6, Eb6, F6 = -9, -4, 0, 3, 6, 8, 9, 12, 15, 18, 20


def fx_tiptoe(rng):
    """The mime's quiet step: a soft muted tap, low and short (played pitched about)."""
    return mix((ping(note_hz(C4), 0.07, 70.0, WOOD, attack=0.004), 0, 1.0),
               (noise(0.03, rng, [(0, 1200), (1, 400)], decay=90.0), 0, 0.3))


def fx_splash(rng):
    """A foot in a puddle: a wet slap of bright noise falling dark, then two bubbles."""
    slap = noise(0.32, rng, [(0, 6000), (0.2, 2200), (1, 500)], decay=12.0, attack=0.001)
    return mix((slap, 0, 1.0), (sweep(500, 1300, 0.05, sine, 0.003, 0.02), 0.07, 0.25),
               (sweep(650, 1600, 0.04, sine, 0.003, 0.02), 0.15, 0.18))


def fx_pipe_burst(rng):
    """A burst pipe starting to gush: a hiss rising in, a clank of the pipe."""
    hiss = highpassed(noise(0.7, rng, [(0, 2000), (0.3, 7000), (1, 5000)], attack=0.08, release=0.35))
    return mix((hiss, 0, 1.0), (ping(310.0, 0.3, 14.0, STEEL), 0, 0.35))


def fx_tilt(rng):
    """A frame knocked askew on its nail: a creak sliding down, then the frame's knock."""
    creak = lowpass(sweep(420, 260, 0.22, saw, 0.02, 0.06), [1800] * int(0.22 * RATE))
    return mix((creak, 0, 0.35), (knock(rng, 200.0), 0.18, 1.0), (knock(rng, 160.0), 0.27, 0.5))


def fx_straighten(rng):
    """A guard righting a frame: two tidy knocks, the second higher."""
    return mix((knock(rng, 170.0), 0, 1.0), (knock(rng, 230.0), 0.12, 0.8))


def fx_hide(rng):
    """Stepping into a painting: a whoosh rising, closing on a soft vibraphone note."""
    whoosh = noise(0.35, rng, [(0, 500), (0.8, 4000), (1, 6000)], attack=0.15, release=0.08)
    return mix((whoosh, 0, 0.7), (ping(note_hz(C6), 0.6, 6.0, VIBES), 0.28, 0.5))


def fx_unhide(rng):
    """Stepping out of a painting: the whoosh falling, from the same note."""
    whoosh = noise(0.35, rng, [(0, 6000), (0.3, 3000), (1, 500)], attack=0.03, release=0.15)
    return mix((ping(note_hz(C6), 0.4, 9.0, VIBES), 0, 0.4), (whoosh, 0.02, 0.7))


def fx_brush(rng):
    """A brush drawn across canvas: a soft bristly swish."""
    return bandpass(noise(0.28, rng, [(0, 6000), (1, 4000)], attack=0.05, release=0.12), 2600.0, 1.2)


def fx_dab(rng):
    """A brush dabbed on canvas: a small damp pop."""
    return mix((bandpass(noise(0.07, rng, [(0, 5000), (1, 2000)], decay=40.0), 1800.0, 2.0), 0, 1.0),
               (sweep(300, 180, 0.06, sine, 0.002, 0.04), 0, 0.4))


def fx_stroke_done(rng):
    """A stroke traced: one pizzicato note (played higher stroke by stroke)."""
    return ping(note_hz(C5), 0.3, 16.0, PIZZ)


def fx_grade_perfect(rng):
    """A perfect fake: a vibraphone arpeggio up an F major chord with a high sparkle."""
    return mix((arpeggio([F4, A4, C5, F5, A5, C6], 0.07, 0.9, 5.0, VIBES), 0, 1.0),
               (ping(note_hz(F6), 1.0, 4.0, BELL), 0.42, 0.3))


def fx_grade_good(rng):
    """A good fake: two plucked notes up a fifth, content."""
    return arpeggio([F4, C5], 0.12, 0.5, 8.0, PIZZ)


def fx_grade_sloppy(rng):
    """A sloppy fake: a wobbly muted horn sliding down (the comic 'wah-wah')."""
    n = int(0.7 * RATE)
    freqs = [h * (1.0 + 0.025 * math.sin(2 * math.pi * 6.0 * i / RATE)) for i, h in enumerate(lerp_curve([(0, 233), (0.4, 220), (1, 175)], n))]
    tone = lowpass(oscillate(freqs, saw), lerp_curve([(0, 600), (0.3, 1400), (1, 500)], n))
    return [s * e for s, e in zip(tone, envelope(n, 0.03, 0.2))]


def fx_swap(rng):
    """The original lifted and the fake hung: a scrape, a click on the hook, a pleased note."""
    scrape = bandpass(noise(0.2, rng, [(0, 3000), (1, 2000)], attack=0.03, release=0.05), 1200.0, 1.5)
    return mix((scrape, 0, 0.6), (knock(rng, 260.0, 0.06), 0.2, 1.0), (ping(note_hz(F5), 0.5, 7.0, VIBES), 0.26, 0.45))


def fx_door(rng):
    """Slipping through a door: a short creak and a soft thud as it swings to."""
    creak = lowpass(sweep(300, 380, 0.2, saw, 0.03, 0.05), [1400] * int(0.2 * RATE))
    return mix((creak, 0, 0.3), (thump(90.0, 0.2, 0.5, 20.0), 0.18, 1.0), (knock(rng, 140.0), 0.18, 0.4))


def fx_chain_rattle(rng):
    """A locked wing's chain rattling: a jangle of small steel links."""
    buf = []
    for k in range(6):
        place(buf, ping(rng.uniform(1700, 2600), 0.12, 35.0, STEEL), k * 0.045 + rng.uniform(0, 0.015), rng.uniform(0.5, 1.0))
    return buf


def fx_caught(rng):
    """A guard grabbing the mime: a cartoon bonk with a springy boing."""
    n = int(0.45 * RATE)
