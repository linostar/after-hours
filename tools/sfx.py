def wav_bytes(samples, peak=PEAK):
    if peak > PEAK:
        raise SfxError(f"peak {peak} is above PEAK {PEAK}")
    top = max(abs(s) for s in samples) or 1.0
    frames = b"".join(struct.pack("<h", int(s / top * peak * 32767)) for s in samples)
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(frames)
    return buffer.getvalue()


def sounds():
    """{file name: WAV bytes} for every sound, in a fixed order."""
    files = {}
    for name, (generate, peak, _band) in EFFECTS.items():
        # Each effect has its own noise seed, so editing one never changes another.
        files[f"{name}.wav"] = wav_bytes(generate(random.Random(f"sfx/{name}")), peak)
    return files


# Loudness: ITU-R BS.1770 K-weighting (its two filters, derived for RATE), then the mean
# square over the loudest LOUDNESS_WINDOW seconds (stepped every LOUDNESS_HOP), in LUFS.
LOUDNESS_WINDOW = 0.1
LOUDNESS_HOP = 0.01


def biquad(samples, b, a):
    out, x1, x2, y1, y2 = [], 0.0, 0.0, 0.0, 0.0
    for x in samples:
        y = b[0] * x + b[1] * x1 + b[2] * x2 - a[0] * y1 - a[1] * y2
        out.append(y)
        x2, x1, y2, y1 = x1, x, y1, y
    return out


def k_weighted(samples, rate=RATE):
    """BS.1770's K-weighting at `rate` Hz: a high shelf (+4 dB above ~1.7 kHz) and a
    high-pass (~38 Hz). tools/music.py uses it too."""
    k = math.tan(math.pi * 1681.974450955533 / rate)
    q = 0.7071752369554196
    vh = 10 ** (3.999843853973347 / 20)
    vb = vh ** 0.4996667741545416
    a0 = 1 + k / q + k * k
    shelf = biquad(samples, ((vh + vb * k / q + k * k) / a0, 2 * (k * k - vh) / a0, (vh - vb * k / q + k * k) / a0),
                   (2 * (k * k - 1) / a0, (1 - k / q + k * k) / a0))
    k = math.tan(math.pi * 38.13547087602444 / rate)
    q = 0.5003270373238773
    a0 = 1 + k / q + k * k
    return biquad(shelf, (1.0, -2.0, 1.0), (2 * (k * k - 1) / a0, (1 - k / q + k * k) / a0))


def loudness_of(data):
    """The loudness of WAV bytes as heard: K-weighted, the loudest LOUDNESS_WINDOW, in LUFS."""
    with wave.open(io.BytesIO(data), "rb") as w:
        frames = w.readframes(w.getnframes())
    weighted = k_weighted([v / 32767 for (v,) in struct.iter_unpack("<h", frames)])
    window, hop = int(LOUDNESS_WINDOW * RATE), int(LOUDNESS_HOP * RATE)
    squares = [y * y for y in weighted] + [0.0] * window
    total = sum(squares[:window])
    loudest = total
    for start in range(hop, len(weighted), hop):
        total = sum(squares[start:start + window])
        loudest = max(loudest, total)
    return -0.691 + 10 * math.log10(max(loudest / window, 1e-12))


def seconds_of(data):
    """The length of WAV bytes in seconds."""
    with wave.open(io.BytesIO(data), "rb") as w:
        return w.getnframes() / w.getframerate()


def peak_of(data):
    """The largest absolute sample of WAV bytes, as a fraction of full scale."""
    with wave.open(io.BytesIO(data), "rb") as w:
        frames = w.readframes(w.getnframes())
    return max(abs(v) for (v,) in struct.iter_unpack("<h", frames)) / 32767


def band_of(name):
    """The loudness band (LOUDNESS_BANDS) of sound file `name`."""
    return EFFECTS[name.removesuffix(".wav")][2]


def check():
    files = sounds()
    problems = []
    total_bytes = 0
    for name, data in files.items():
        if peak_of(data) > PEAK:
            problems.append(f"{name} peaks at {peak_of(data):.3f}, above PEAK {PEAK}")
        band = band_of(name)
        low, high = LOUDNESS_BANDS[band]
        loudness = loudness_of(data)
        if not low <= loudness <= high:
            problems.append(f"{name} is {loudness:.1f} LUFS, outside its {band} band {low}..{high} LUFS (loudness_of)")
        committed = OUT_DIR / name
        if not committed.exists():
            problems.append(f"{committed.relative_to(ROOT)} missing, run python3 tools/sfx.py")
            continue
        total_bytes += committed.stat().st_size
        if committed.read_bytes() != data:
            problems.append(f"{committed.relative_to(ROOT)} differs from its synth, run python3 tools/sfx.py")
        if not Path(str(committed) + ".import").exists():
            problems.append(f"{committed.relative_to(ROOT)}.import missing: import the project (Godot --import) and commit it")
    for path in sorted(OUT_DIR.glob("*.wav")):
        if path.name not in files:
            problems.append(f"{path.relative_to(ROOT)} is stale: no sound makes it any more")
    if total_bytes > MAX_TOTAL_BYTES:
        problems.append(f"the sound effects total {total_bytes} bytes, over {MAX_TOTAL_BYTES}")
    if problems:
        raise SfxError("\n".join(problems))
    print(f"sfx: OK ({len(files)} sounds, {total_bytes} bytes)")


def main():
    try:
        if sys.argv[1:] == ["--check"]:
            check()
        elif not sys.argv[1:]:
            OUT_DIR.mkdir(parents=True, exist_ok=True)
            files = sounds()
            for name, data in files.items():
                (OUT_DIR / name).write_bytes(data)
            print(f"sfx: wrote {len(files)} sounds to {OUT_DIR.relative_to(ROOT)}")
        else:
            print(__doc__, file=sys.stderr)
            return 2
    except SfxError as e:
        print(f"sfx: error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
