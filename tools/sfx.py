#!/usr/bin/env python3
"""Synthesises After Hours' sound effects as 16-bit mono WAV.

Standard library only and fully deterministic (fixed seeds, no clock), so the committed
files can always be regenerated byte-for-byte. Synth core and checks ported from Hunt Frenzy's
tools/sfx.py (../hunt-frenzy, itself from BrewMagic's): one-pole low-pass, RBJ band-pass,
linear envelopes, piecewise curves, peak-normalised 16-bit writer, BS.1770 loudness. Every
sound is designed here from scratch for this game (a caper band of pizzicato strings,
vibraphone and wood blocks, echoing tools/music.py); no sample, jingle or effect of any
other game is copied or imitated.

Sounds:
    <name>.wav    every game sound effect of EFFECTS (one generator each, its own noise seed
                  and peak level), played through Game.audio.play(name); the list is
                  Audio.SFX_IDS (a test checks both agree).

Every file is peak-normalised to its own level, never above PEAK, so nothing clips; the
levels set the mix, and --check holds each file's loudness as heard (loudness_of: BS.1770
K-weighting, the loudest 0.1 s) inside its kind's LOUDNESS_BANDS. Each file's .import must
exist (Godot imports it, so it ships).

Usage (from repo root):
    python3 tools/sfx.py           write every sound into afterhours/audio/sfx/
    python3 tools/sfx.py --check   regenerate in memory and verify the committed files are
                                   byte-identical, imported, inside their loudness bands
                                   and none is stale; prints "sfx: OK"
"""
import io
import math
import random
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
